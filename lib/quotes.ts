/** Random quote for this hour, skipping recently shown ones. */
export function pickQuote(now: Date, recent: string[], random: () => number = Math.random): Quote {
  const hour = now.getHours();
  const night = hour >= 21 || hour < 6;
  const pool = QUOTES.filter((q) => !q.night || night);
  const fresh = pool.filter((q) => !recent.includes(q.id));
  const list = fresh.length ? fresh : pool;
  return list[Math.floor(random() * list.length)];
}
